import { randomBytes } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';

function parseArgs(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg.startsWith('--') && arg.includes('=')) {
      const [key, value] = arg.slice(2).split(/=(.*)/su, 2);
      result[key] = value;
    } else if (arg.startsWith('--')) result[arg.slice(2)] = argv[++index];
    else throw new Error(`unexpected argument ${arg}`);
  }
  return result;
}

function ensureChild(root, candidate) {
  const resolvedRoot = resolve(root);
  const resolvedCandidate = resolve(candidate);
  if (!resolvedCandidate.startsWith(`${resolvedRoot}${sep}`)) {
    throw new Error(`refusing target outside ${resolvedRoot}: ${resolvedCandidate}`);
  }
  return resolvedCandidate;
}

function backupName() {
  return new Date().toISOString().replace(/[:.]/gu, '-');
}

const args = parseArgs(process.argv.slice(2));
if (!args['dsh-home'] || !args.mode || !args['dsh-version']) {
  throw new Error('required: --dsh-home, --mode, --dsh-version');
}
if (!['lean', 'balanced'].includes(args.mode)) throw new Error('--mode must be lean or balanced');

const dshHome = resolve(args['dsh-home']);
const profileRoot = join(dshHome, 'profiles');
const target = ensureChild(profileRoot, join(profileRoot, 'skillopt-headless'));
const markerName = '.dsh-codex-kit.json';
if (existsSync(target) && !existsSync(join(target, markerName))) {
  throw new Error(`refusing to overwrite unowned profile: ${target}`);
}

const patch = args.mode === 'lean' ? `# Generated by dsh-codex-kit. Re-run the installer after DSH upgrades.
- id: tool-skill
  disabled: true

- id: agent-instructions
  config:
    maxBytes: 32768

- id: tool-result-pruner
  config:
    thresholdChars: 6144
    headChars: 3072
    tailChars: 1024
` : `# Balanced mode keeps the upstream catalog and budgets.
[]
`;

mkdirSync(profileRoot, { recursive: true });
const temporary = `${target}.tmp-${process.pid}-${randomBytes(4).toString('hex')}`;
rmSync(temporary, { recursive: true, force: true });
mkdirSync(temporary, { recursive: true });
writeFileSync(join(temporary, 'package.json'), `${JSON.stringify({
  name: 'dsh-profile-skillopt-headless',
  private: true,
  dependencies: {},
  dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless'] } },
}, null, 2)}\n`, 'utf8');
writeFileSync(join(temporary, 'pnpm-workspace.yaml'), 'packages: []\n', 'utf8');
writeFileSync(join(temporary, 'cordis.yml'), '[]\n', 'utf8');
writeFileSync(join(temporary, 'cordis.patch.yml'), patch, 'utf8');
writeFileSync(join(temporary, markerName), `${JSON.stringify({
  owner: 'dsh-codex-kit',
  kitVersion: '0.2.0',
  dshVersion: args['dsh-version'],
  mode: args.mode,
  generatedAt: new Date().toISOString(),
}, null, 2)}\n`, 'utf8');

let backup;
try {
  if (existsSync(target)) {
    backup = join(dshHome, 'backups', 'dsh-codex-kit', `${backupName()}-skillopt-headless`);
    mkdirSync(dirname(backup), { recursive: true });
    cpSync(target, backup, {
      recursive: true,
      errorOnExist: true,
      force: false,
      filter: (source) => !source.split(/[\\/]/u).includes('node_modules'),
    });
    rmSync(target, { recursive: true, force: false });
  }
  renameSync(temporary, target);
} catch (error) {
  rmSync(temporary, { recursive: true, force: true });
  if (!existsSync(target) && backup && existsSync(backup)) cpSync(backup, target, { recursive: true });
  throw error;
}
console.log(JSON.stringify({ status: 'created', target, backup, mode: args.mode }));
